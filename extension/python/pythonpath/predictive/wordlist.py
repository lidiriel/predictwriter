"""Sorted word list with bisect prefix search (plain Python, no ``uno``).

File format (generated by ``tools/build_wordlist.py``): one
``word<TAB>frequency[<TAB>verb_bits<TAB>elision_bits]`` line per word form,
sorted by :func:`lookup_key`. The optional bit masks are described in
``predictive.grammar``.
"""

from array import array
from bisect import bisect_left
from typing import Dict, List, Optional, Sequence, Tuple

# Sorts after any character found in a word list: used as an upper bound.
_HIGH = "\U0010ffff"
# Above this many words in a prefix range, an elision-filtered search walks
# the precomputed per-elision list (best first) instead of the range.
_RANGE_SCAN_LIMIT = 3000

Entry = Tuple  # (word, freq) or (word, freq, verb_bits, elision_bits)


def lookup_key(word: str) -> str:
    """Normalised key used for sorting and lookup.

    Lower-cases and maps the typographic apostrophe (U+2019) to ASCII, so that
    ``l’arbre`` and ``l'arbre`` match the same entries. Keep in sync with
    ``tools/build_wordlist.py``.
    """
    return word.lower().replace("’", "'")


def merge_by_key(entries: Sequence[Entry]) -> Dict[str, Tuple]:
    """Keep one entry per lookup key.

    The most frequent spelling wins, lower-case winning ties; bit masks (if
    any) are combined ("Paris" and "paris" share the key "paris"). Entries
    whose case mapping changes their length are dropped.
    """
    best: Dict[str, Tuple] = {}
    for entry in entries:
        word, freq = entry[0], entry[1]
        key = lookup_key(word)
        if not word or len(key) != len(word) or "\n" in key:
            continue
        prev = best.get(key)
        if prev is None:
            best[key] = tuple(entry)
            continue
        extra = tuple(a | b for a, b in zip(prev[2:], entry[2:]))
        if (freq, word == key) > (prev[1], prev[0] == key):
            best[key] = (word, freq) + extra
        else:
            best[key] = (prev[0], prev[1]) + extra
    return best


def _parse(line: str) -> Tuple[str, int, int, int]:
    fields = line.rstrip("\n").split("\t")
    word = fields[0]
    nums = [int(f) if f.isdigit() else 0 for f in fields[1:4]]
    nums += [0] * (3 - len(nums))
    return word, nums[0], nums[1], nums[2]


def _read_entries(path: str) -> List[Tuple[str, int, int, int]]:
    with open(path, encoding="utf-8") as fh:
        return [_parse(line) for line in fh]


class _KeySequence:
    """Read-only sequence of keys stored in one string (saves ~80% memory).

    ``bisect`` only needs ``__len__`` and ``__getitem__``.
    """

    def __init__(self, keys: List[str]) -> None:
        self._blob = "\n".join(keys)
        offsets = array("i", [0])
        pos = 0
        for key in keys:
            pos += len(key) + 1
            offsets.append(pos)
        self._offsets = offsets

    def __len__(self) -> int:
        return len(self._offsets) - 1

    def __getitem__(self, i: int) -> str:
        return self._blob[self._offsets[i] : self._offsets[i + 1] - 1]


class WordList:
    """In-memory prefix index over one language's word forms."""

    def __init__(self) -> None:
        self._keys = _KeySequence([])
        # Dictionary spelling, only where it differs from the key ("Paris").
        self._spelling: Dict[int, str] = {}
        self._freqs = array("i")
        self._verbs = array("i")  # verb bits (predictive.grammar)
        self._elisions = array("i")  # elision bits (predictive.grammar)
        self.has_grammar = False
        # Global rank of each entry (0 = best), so that ranking a prefix range
        # is a C-level sort of small ints rather than a Python key function.
        self._rank = array("i")
        self._by_rank = array("i")
        self._by_elision: Dict[int, "array[int]"] = {}  # bit -> indices, best first
        # Frequent elided pairs (<lang>.elisions.tsv): bit -> indices, best first.
        self._pairs: Dict[int, "array[int]"] = {}
        # Verb forms only, best first: all of them, and per elision bit.
        self._verbs_by_rank: "array[int]" = array("i")
        self._verbs_by_elision: Dict[int, "array[int]"] = {}

    def __len__(self) -> int:
        return len(self._keys)

    @classmethod
    def load(cls, path: str) -> "WordList":
        """Load a word list file.

        Files from ``tools/build_wordlist.py`` are sorted by key without
        duplicates and are streamed directly; any other file falls back to
        :meth:`from_entries` (slower, more memory).
        """
        keys: List[str] = []
        spelling: Dict[int, str] = {}
        columns = (array("i"), array("i"), array("i"))
        prev = ""
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                word, freq, verb, elision = _parse(line)
                key = lookup_key(word)
                if not word or len(key) != len(word):
                    continue
                if key <= prev:
                    return cls.from_entries(_read_entries(path))
                if word != key:
                    spelling[len(keys)] = word
                keys.append(key)
                columns[0].append(freq)
                columns[1].append(verb)
                columns[2].append(elision)
                prev = key
        return cls._from_sorted(keys, spelling, *columns)

    @classmethod
    def from_entries(cls, entries: Sequence[Entry]) -> "WordList":
        """Build from ``(word, freq[, verb_bits, elision_bits])``, in any order.

        Entries sharing a key (``Paris``/``paris``) are merged: the most
        frequent spelling wins, lower-case winning ties.
        """
        best = merge_by_key(entries)
        keys = sorted(best)
        spelling: Dict[int, str] = {}
        columns = (array("i"), array("i"), array("i"))
        for index, key in enumerate(keys):
            entry = tuple(best[key]) + (0, 0)
            if entry[0] != key:
                spelling[index] = entry[0]
            for column, value in zip(columns, entry[1:4]):
                column.append(value)
        return cls._from_sorted(keys, spelling, *columns)

    @classmethod
    def _from_sorted(
        cls,
        keys: List[str],
        spelling: Dict[int, str],
        freqs: "array[int]",
        verbs: "array[int]",
        elisions: "array[int]",
    ) -> "WordList":
        self = cls()
        self._spelling = spelling
        self._freqs = freqs
        self._verbs = verbs
        self._elisions = elisions
        self.has_grammar = any(elisions) or any(verbs)
        # Rank by (-freq, length, key) using packed ints: much lighter than
        # sorting tuples. Index order is key order, so it breaks ties.
        top = max(freqs, default=0)
        packed = sorted(
            ((top - f) << 48) | (min(len(k), 0xFFFF) << 32) | i
            for i, (k, f) in enumerate(zip(keys, freqs))
        )
        self._by_rank = array("i", (p & 0xFFFFFFFF for p in packed))
        del packed
        self._rank = array("i", bytes(len(keys) * self._rank.itemsize))
        for rank, index in enumerate(self._by_rank):
            self._rank[index] = rank
        self._keys = _KeySequence(keys)
        return self

    # Access by index ---------------------------------------------------------
    def word(self, index: int) -> str:
        """Dictionary spelling of entry ``index``."""
        return self._spelling.get(index) or self._keys[index]

    _word = word  # backwards-compatible alias

    def verb_bits(self, index: int) -> int:
        return self._verbs[index]

    def elision_bits(self, index: int) -> int:
        return self._elisions[index]

    def index_of(self, word: str) -> Optional[int]:
        """Index of ``word`` (case-insensitively), or None."""
        key = lookup_key(word)
        i = bisect_left(self._keys, key)
        if i < len(self._keys) and self._keys[i] == key:
            return i
        return None

    # Searches ------------------------------------------------------------------
    def candidates(
        self, prefix: str, limit: int, elision_bit: int = 0, verb_mask: int = 0
    ) -> List[int]:
        """Indices of up to ``limit`` words starting with ``prefix``, best first.

        The prefix itself is excluded. With ``elision_bit``, only words that
        accept that elided word (``l'``, ``j'``...) are returned; ``prefix``
        may then be empty ("j'" -> all words that may follow "j'"). With
        ``verb_mask``, only words with one of these verb bits are returned.
        """
        if verb_mask:
            return self._verb_candidates(prefix, limit, elision_bit, verb_mask)
        key = lookup_key(prefix)
        if limit <= 0 or (not key and not elision_bit):
            return []
        lo = bisect_left(self._keys, key) if key else 0
        hi = bisect_left(self._keys, key + _HIGH, lo) if key else len(self._keys)
        if key and lo < hi and self._keys[lo] == key:
            lo += 1  # the exact word is sorted first in its range
        if lo >= hi:
            return []
        if not elision_bit:
            return [self._by_rank[r] for r in sorted(self._rank[lo:hi])[:limit]]
        # Frequent elided pairs first ("l'" -> "année", "un"...), then the
        # other words accepting the elision, by frequency.
        result: List[int] = []
        seen = set()
        for index in self._pairs.get(elision_bit, ()):
            k = self._keys[index]
            if k.startswith(key) and k != key:
                result.append(index)
                seen.add(index)
                if len(result) >= limit:
                    return result
        limit -= len(result)
        if hi - lo <= _RANGE_SCAN_LIMIT:
            elisions = self._elisions
            ranks = sorted(
                self._rank[i]
                for i in range(lo, hi)
                if elisions[i] & elision_bit and i not in seen
            )
            return result + [self._by_rank[r] for r in ranks[:limit]]
        # Large range (short prefix): walk the words accepting this elision,
        # best first, and keep those with the prefix.
        added = 0
        for index in self._elision_list(elision_bit):
            k = self._keys[index]
            if k.startswith(key) and k != key and index not in seen:
                result.append(index)
                added += 1
                if added >= limit:
                    break
        return result

    def _verb_candidates(
        self, prefix: str, limit: int, elision_bit: int, verb_mask: int
    ) -> List[int]:
        """Best words with ``verb_mask`` bits (and the elision, if any)."""
        key = lookup_key(prefix)
        verbs, elisions, keys = self._verbs, self._elisions, self._keys
        lo = bisect_left(keys, key) if key else 0
        hi = bisect_left(keys, key + _HIGH, lo) if key else len(keys)
        if lo >= hi or limit <= 0:
            return []
        if hi - lo <= _RANGE_SCAN_LIMIT * 5:
            ranks = sorted(
                self._rank[i]
                for i in range(lo, hi)
                if verbs[i] & verb_mask
                and (not elision_bit or elisions[i] & elision_bit)
                and keys[i] != key
            )
            return [self._by_rank[r] for r in ranks[:limit]]
        # Large range (short or empty prefix): walk verb forms only.
        if elision_bit:
            source = self._verbs_by_elision.get(elision_bit)
            if source is None:
                source = array(
                    "i", (i for i in self._elision_list(elision_bit) if verbs[i])
                )
        else:
            source = self._verbs_by_rank or self._by_rank
        result = []
        for index in source:
            if verbs[index] & verb_mask:
                k = keys[index]
                if k.startswith(key) and k != key:
                    result.append(index)
                    if len(result) >= limit:
                        break
        return result

    def load_elision_pairs(self, path: str) -> int:
        """Load ``elision<TAB>word<TAB>score`` lines (best first per elision)."""
        from predictive.grammar import ELISION_BIT

        lists: Dict[int, "array[int]"] = {}
        with open(path, encoding="utf-8") as fh:
            for line in fh:
                fields = line.rstrip("\n").split("\t")
                if len(fields) < 2 or fields[0] not in ELISION_BIT:
                    continue
                index = self.index_of(fields[1])
                if index is not None:
                    lists.setdefault(ELISION_BIT[fields[0]], array("i")).append(index)
        self._pairs = lists
        return sum(len(v) for v in lists.values())

    def prepare_elisions(self) -> None:
        """Precompute per-elision and verb lists (one pass; no slow first use)."""
        if not self.has_grammar:
            return
        lists: Dict[int, "array[int]"] = {}
        verb_lists: Dict[int, "array[int]"] = {}
        all_verbs = array("i")
        elisions, verbs = self._elisions, self._verbs
        for index in self._by_rank:
            is_verb = verbs[index] != 0
            if is_verb:
                all_verbs.append(index)
            bits = elisions[index]
            while bits:
                bit = bits & -bits
                lists.setdefault(bit, array("i")).append(index)
                if is_verb:
                    verb_lists.setdefault(bit, array("i")).append(index)
                bits ^= bit
        self._by_elision = lists
        self._verbs_by_elision = verb_lists
        self._verbs_by_rank = all_verbs

    def _elision_list(self, bit: int) -> "array[int]":
        cached = self._by_elision.get(bit)
        if cached is None:
            elisions = self._elisions
            cached = array("i", (i for i in self._by_rank if elisions[i] & bit))
            self._by_elision[bit] = cached
        return cached

    def complete(self, prefix: str, n: int = 5) -> List[str]:
        """Return up to ``n`` dictionary words starting with ``prefix``.

        Words are returned in dictionary spelling, best first (frequency, then
        shorter words, then alphabetical). The prefix itself is never returned.
        """
        return [self.word(i) for i in self.candidates(prefix, n)]

    def contains(self, word: str) -> bool:
        """True if ``word`` (case-insensitively) is in the list."""
        return self.index_of(word) is not None

    def spelling(self, word: str) -> Optional[str]:
        """Dictionary spelling of ``word`` ("paris" -> "Paris"), None if unknown."""
        index = self.index_of(word)
        return None if index is None else self.word(index)

    def frequency(self, word: str) -> Optional[int]:
        """Frequency of ``word``, or None if unknown."""
        index = self.index_of(word)
        return None if index is None else self._freqs[index]
